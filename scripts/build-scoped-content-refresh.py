#!/usr/bin/env python3
"""Build the guarded SQL patch for a reviewed monthly answer refresh.

This builder is deliberately scoped to rows marked time-dependent. It does not
connect to Supabase and does not apply the resulting SQL. Update the reviewed
catalog first, then regenerate the ordinary reproducible seed separately.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "research/2026-10-27/answers"
OUTPUT = ROOT / "supabase/content-updates/2026-11-07-time-dependent-refresh.sql"
REVIEWED_ON = "2026-11-07"
PREVIOUSLY_REVIEWED_ON = "2026-10-27"
COUNTS = {"2008": 566, "2025": 565}
BASELINE_FINGERPRINTS = {
    "2008": "eaed309e35f7bf050eb10ce56540a166",
    "2025": "52a07e322f87f205c32e7e8e7ba68b1d",
}
OK_GUIDANCE = {
    ("2008", 20): "US-OK",
    ("2025", 23): "US-OK",
}


def sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def guidance_target(edition: str, question_number: int, geography: str) -> dict:
    guide = json.loads((CATALOG / "change-guidance.json").read_text())
    matches = [
        row for row in guide["records"]
        if row["edition"] == edition
        and row["question_number"] == question_number
        and row["geography"] == geography
    ]
    if len(matches) != 1:
        raise ValueError(f"Expected one reviewed guidance row for {edition} Q{question_number} {geography}")
    return matches[0]


def build_sql() -> str:
    # Validate the exact reviewed scope against the local answer catalogs.
    dynamic_questions: dict[str, set[int]] = {}
    for edition in ("2008", "2025"):
        bank = json.loads((CATALOG / f"answers-{edition}.json").read_text())
        dynamic_questions[edition] = {
            row["official_number"] for row in bank["questions"]
            if row.get("volatility") in {"medium", "high"}
        }
    rows = {"2008": 0, "2025": 0}
    with (CATALOG / "resolved-answers.csv").open(newline="") as stream:
        import csv
        for row in csv.DictReader(stream):
            edition = row["edition_id"].removeprefix("uscis-")
            if int(row["official_number"]) in dynamic_questions[edition]:
                rows[edition] += 1
    if rows != COUNTS:
        raise ValueError(f"Reviewed dynamic row counts changed: {rows}; expected {COUNTS}")

    lines = [
        "-- Generated by scripts/build-scoped-content-refresh.py.",
        "-- Data-only patch. Apply only after reviewing source checks and local diff.",
        "-- Exact before-state fingerprints prevent applying to a changed database.",
        "begin;",
        "do $$",
        "declare v_fingerprint text;",
        "begin",
    ]
    for edition, table in (("2008", "civics_questions_2008"), ("2025", "civics_questions_2025")):
        lines.extend([
            f"  select md5(string_agg(row(question_number, geography, answers, answer_display, answer_status, previous_officeholder, answer_updated_on, next_update_on, expected_change_on, expected_change_through, change_expectation, change_guidance, review_flagged_on, review_flag_reason)::text, E'\\n' order by question_number, geography))",
            f"    into v_fingerprint from public.{table};",
            f"  if v_fingerprint is distinct from {sql_literal(BASELINE_FINGERPRINTS[edition])} then",
            f"    raise exception 'content refresh baseline fingerprint mismatch for {edition}';",
            "  end if;",
        ])
    lines.extend(["end $$;", "do $$", "declare v_changed integer;", "begin"])
    for edition, table in (("2008", "civics_questions_2008"), ("2025", "civics_questions_2025")):
        lines.extend([
            f"  update public.{table}",
            f"     set answer_updated_on = date '{REVIEWED_ON}'",
            f"   where is_time_dependent and answer_updated_on = date '{PREVIOUSLY_REVIEWED_ON}';",
            "  get diagnostics v_changed = row_count;",
            f"  if v_changed <> {COUNTS[edition]} then",
            f"    raise exception 'expected {COUNTS[edition]} reviewed time-dependent rows in {edition}, changed %', v_changed;",
            "  end if;",
        ])
    lines.extend(["end $$;", "do $$", "declare v_changed integer;", "begin"])
    senate_old = "https://www.senate.gov/general/resources/pdf/senators_phone_list.pdf"
    senate_new = "https://www.senate.gov/general/contact_information/senators_cfm.xml"
    senate_source = {
        "id": "senate_current_xml",
        "url": senate_new,
        "source_type": "official_current_senate_directory_xml",
        "source_published_on": "2026-11-06",
        "verified_on": REVIEWED_ON,
        "sha256": "c41ea0f442e7a4546a29279929029bb12386ebff73b4735ffe7e0bde3234f0d5",
    }
    senate_source_json = sql_literal(json.dumps(senate_source, separators=(",", ":"))) + "::jsonb"
    for edition, table, question_number in (("2008", "civics_questions_2008", 20), ("2025", "civics_questions_2025", 23)):
        lines.extend([
            f"  update public.{table} as q",
            f"     set source_urls = array_replace(q.source_urls, {sql_literal(senate_old)}, {sql_literal(senate_new)}),",
            "         source_details = coalesce((",
            "           select jsonb_agg(case when item.value->>'id' = 'senate_phone' then " + senate_source_json + " else item.value end order by item.ordinality)",
            "           from jsonb_array_elements(q.source_details) with ordinality as item(value, ordinality)",
            "         ), '[]'::jsonb)",
            f"   where q.question_number = {question_number} and q.is_time_dependent",
            f"     and {sql_literal(senate_old)} = any(q.source_urls);",
            "  get diagnostics v_changed = row_count;",
            "  if v_changed <> 50 then",
            f"    raise exception 'expected 50 reviewed Senate source rows in {edition}, changed %', v_changed;",
            "  end if;",
        ])
    scotus_url = "https://www.supremecourt.gov/about/biographies.aspx"
    scotus_source = {
        "id": "scotus_current_justice",
        "url": scotus_url,
        "source_type": "official_current_supreme_court_membership",
        "verified_on": REVIEWED_ON,
    }
    scotus_json = sql_literal(json.dumps(scotus_source, separators=(",", ":"))) + "::jsonb"
    lines.extend([
        "  update public.civics_questions_2025",
        "     set source_urls = array_append(source_urls, " + sql_literal(scotus_url) + "),",
        "         source_details = source_details || jsonb_build_array(" + scotus_json + ")",
        "   where question_number = 57 and geography = 'US'",
        "     and answer_updated_on = date '2026-11-07'",
        "     and answers = array['John Roberts', 'John G. Roberts, Jr.', 'Roberts']::text[]",
        "     and not (" + sql_literal(scotus_url) + " = any(source_urls));",
        "  get diagnostics v_changed = row_count;",
        "  if v_changed <> 1 then raise exception 'expected one guarded 2025 Q57 provenance row, changed %', v_changed; end if;",
    ])
    lines.extend(["end $$;", "do $$", "declare v_changed integer;", "begin"])
    for edition, question_number in OK_GUIDANCE:
        table = f"civics_questions_{edition}"
        target = guidance_target(edition, question_number, "US-OK")
        payload = json.dumps(target["change_guidance"], ensure_ascii=False, separators=(",", ":"))
        lines.extend([
            f"  update public.{table}",
            "     set expected_change_on = date '2026-11-03',",
            "         expected_change_through = date '2027-01-03',",
            "         change_expectation = 'estimated_window',",
            f"         change_guidance = {sql_literal(payload)}::jsonb",
            f"   where question_number = {question_number} and geography = 'US-OK'",
            "     and expected_change_on = date '2027-01-03'",
            "     and change_guidance->'answer_candidates' @> '[{\"answer\":\"Alan Armstrong\",\"expected_change_on\":\"2027-01-03\"}]'::jsonb;",
            "  get diagnostics v_changed = row_count;",
            "  if v_changed <> 1 then",
            f"    raise exception 'expected one guarded Oklahoma guidance row for {edition}, changed %', v_changed;",
            "  end if;",
        ])
    lines.extend(["end $$;", "commit;", ""])
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    sql = build_sql()
    OUTPUT.write_text(sql)
    print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(sql.encode())} bytes)")
